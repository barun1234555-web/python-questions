# A sample list of numbers
numbers = [42, 17, 89, 12, 55]

# 1. len() - Returns the number of elements
print(f"List length: {len(numbers)}")

# 2. max() - Returns the largest element
print(f"Maximum value: {max(numbers)}")

# 3. min() - Returns the smallest element
print(f"Minimum value: {min(numbers)}")

# 4. sum() - Returns the total sum of all elements
print(f"Total sum: {sum(numbers)}")

# 5. sorted() - Returns a new list that is sorted (original stays same)
print(f"Sorted list (Ascending): {sorted(numbers)}")
print(f"Original list remains unchanged: {numbers}")